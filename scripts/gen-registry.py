#!/usr/bin/env python3
# =============================================================================
# gen-registry.py — 统一平台词汇表/权限矩阵生成器（R-2，2026-10-11）
#
# 单一事实源：docs/registry/registry.yaml
# 生成物：
#   1. user-server/internal/rbac/permissions_gen.go（权限点常量 + 角色→权限矩阵）
#   2. docs/registry/generated/api-vocabulary.md（人读版）
#
# 用法：
#   python scripts/gen-registry.py             # 生成（覆盖生成物）
#   python scripts/gen-registry.py --check     # 校验生成物是否新鲜（CI 用，漂移即 exit 1）
#
# 兼容/回滚：生成物是纯声明（常量与文档），无运行时行为——回滚 = git 回退生成物。
# =============================================================================
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "docs" / "registry" / "registry.yaml"
GO_OUT = ROOT / "user-server" / "internal" / "rbac" / "permissions_gen.go"
MD_OUT = ROOT / "docs" / "registry" / "generated" / "api-vocabulary.md"

# 权限点 id → Go 常量名（customer.read → PermissionCustomerRead）
def go_const(pid: str) -> str:
    # 分隔符统一按 . 与 _ 切段后 CamelCase（api_key.reveal → PermissionApiKeyReveal）
    parts = pid.replace("-", "_").replace(".", "_").split("_")
    return "Permission" + "".join(p.capitalize() for p in parts)


def camel(rid: str) -> str:
    return "".join(p.capitalize() for p in rid.split("_"))


def load():
    data = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    assert data.get("version") == 1, "registry.yaml version 必须为 1"
    return data


def gen_go(data) -> str:
    lines = [
        "// Code generated by scripts/gen-registry.py from docs/registry/registry.yaml. DO NOT EDIT.",
        "// （单一事实源见 registry.yaml；漂移由 TestGeneratedPermissionsFresh 钉住——改权限先改源。）",
        "",
        "// Package rbac 统一平台词汇表/权限矩阵的生成层（ADR-017 R-2）。",
        "// P1 的 RequirePermission 中间件从这里取权限点常量与角色矩阵（backlog P1-1/P1-3）；",
        "// 当前为纯声明，不改变任何路由行为。",
        "package rbac",
        "",
    ]
    lines.append("// 权限点常量（资源.动作）。")
    lines.append("const (")
    for p in data["permissions"]:
        lines.append(f'\t{go_const(p["id"])} = "{p["id"]}"')
    lines.append(")")
    lines.append("")
    lines.append("// RoleAllPermissions 角色 → 权限点集合（P1 中间件的判据源）。")
    lines.append("var RoleAllPermissions = map[string]map[string]bool{")
    roles = data["roles"]
    for rid in roles:
        perms = [p["id"] for p in data["permissions"] if rid in p["roles"]]
        lines.append(f'\t"{rid}": {{')
        for pid in perms:
            lines.append(f'\t\t"{pid}": true,')
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("// RoleHasPermission 判定角色是否持有权限点（P1 中间件单行判据）。")
    lines.append("func RoleHasPermission(role, permission string) bool {")
    lines.append("\tif perms, ok := RoleAllPermissions[role]; ok {")
    lines.append("\t\treturn perms[permission]")
    lines.append("\t}")
    lines.append("\treturn false")
    lines.append("}")
    lines.append("")
    # API Key 状态机常量（与 model.MCPCredentialKey 同口径；测试钉同步）
    lines.append("// API Key 生命周期状态（与 model 层常量同口径，漂移由测试钉住）。")
    lines.append("const (")
    for st in data["api_key_states"]:
        lines.append(f'\tAPIKeyState{camel(st["id"])} = "{st["id"]}"')
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def gen_md(data) -> str:
    out = ["# 平台词汇表与权限矩阵（生成于 registry.yaml，勿手改）", ""]
    out.append("## 词汇表")
    out.append("")
    out.append("| 词汇 | 中文 | 说明 |")
    out.append("|---|---|---|")
    for e in data["entities"]:
        out.append(f'| {e["name"]} | {e["label_zh"]} | {e["notes"]} |')
    out.append("")
    out.append("## 角色")
    out.append("")
    out.append("| 角色 | 中文 | 说明 |")
    out.append("|---|---|---|")
    for rid, r in data["roles"].items():
        out.append(f'| {rid} | {r["label_zh"]} | {r["notes"]} |')
    out.append("")
    out.append("## 权限矩阵")
    out.append("")
    out.append("| 权限点 | 中文 | " + " | ".join(data["roles"].keys()) + " |")
    out.append("|---|---|" + "---|" * len(data["roles"]))
    for p in data["permissions"]:
        marks = " | ".join("✅" if rid in p["roles"] else "—" for rid in data["roles"])
        out.append(f'| `{p["id"]}` | {p["label_zh"]} | {marks} |')
    out.append("")
    out.append("## API Key 状态机")
    out.append("")
    out.append("| 状态 | 中文 | 说明 |")
    out.append("|---|---|---|")
    for st in data["api_key_states"]:
        out.append(f'| `{st["id"]}` | {st["label_zh"]} | {st["notes"]} |')
    out.append("")
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    data = load()
    go_src = gen_go(data)
    md_src = gen_md(data)
    if check:
        bad = []
        if GO_OUT.read_text(encoding="utf-8") != go_src:
            bad.append(str(GO_OUT))
        if MD_OUT.read_text(encoding="utf-8") != md_src:
            bad.append(str(MD_OUT))
        if bad:
            print("❌ 生成物过期（registry.yaml 改了但没重新生成）：", "; ".join(bad))
            sys.exit(1)
        print("✅ 生成物与 registry.yaml 一致")
        return
    GO_OUT.parent.mkdir(parents=True, exist_ok=True)
    MD_OUT.parent.mkdir(parents=True, exist_ok=True)
    GO_OUT.write_text(go_src, encoding="utf-8", newline="\n")
    MD_OUT.write_text(md_src, encoding="utf-8", newline="\n")
    print(f"✅ 已生成 {GO_OUT} / {MD_OUT}")


if __name__ == "__main__":
    main()
