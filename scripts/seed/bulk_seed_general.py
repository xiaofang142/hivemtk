def batch_insert(table, cols, rows):
    """高效批量插入"""
    if not rows:
        return 0
    placeholders = ','.join(['%s'] * len(cols))
    col_str = ','.join(cols)
    sql = f"INSERT INTO {table} ({col_str}) VALUES ({placeholders})"
    cur.executemany(sql, rows)
    return cur.rowcount

