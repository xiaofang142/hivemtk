def gen_faqs(agent_id, category, intent, questions, answers, variants_per=8):
    """生成 FAQ: 每个 question × answers × variants 变体"""
    rows = []
    for q_tmpl in questions:
        for a_tmpl in answers:
            for v in range(variants_per):
                v_tag = f"v{v+1}" if variants_per > 1 else ""
                q = fill(q_tmpl, {'v': v_tag})
                a = fill(a_tmpl, {'v': v_tag})
                keywords = list(set(re.findall(r'[\u4e00-\u9fff]+', q)))[:6]
                rows.append((
                    q + ' [ind-seed]', a + ' [ind-seed]',
                    keywords, category, intent,
                    0.85, agent_id, 0.7, True, 0, NOW, NOW
                ))
    return rows

def gen_sops(agent_id, intent, stage, scenarios):
    rows = []
    for i, (name, tmpl) in enumerate(scenarios):
        rows.append((
            f"{name} [ind-seed]", intent, stage, fill(tmpl, {}), '{}',
            90 - i, 0.85, agent_id, True, 0, NOW, NOW
        ))
    return rows

def gen_rag(product_id, name, desc, category, agent_id, doc_defs):
    """创建 RAG 产品 + 文档 + chunks"""
    cur.execute("""
        INSERT INTO rag_products (id, name, description, category, vector_table)
        VALUES (%s, %s, %s, %s, %s) ON CONFLICT (id) DO NOTHING
    """, (product_id, name, desc, category, f'rag_{product_id}'))
    
    doc_count = 0
    chunk_count = 0
    
    for title, filename, cat, priority, chunks in doc_defs:
        cur.execute("""
            INSERT INTO knowledge_documents 
            (product_id, title, filename, file_type, source_type, category, priority,
             content, embed_status, status, agent_id, metadata, created_at, updated_at)
            VALUES (%s,%s,%s,'md','system_seed',%s,%s,%s,'indexed',1,%s,%s,NOW(),NOW())
            RETURNING id
        """, (product_id, title, filename, cat, priority, ' '.join(chunks), agent_id,
              json.dumps({"source": "ind-seed"})))
        doc_id = cur.fetchone()[0]
        doc_count += 1
        
        for idx, c in enumerate(chunks):
            cur.execute("""
                INSERT INTO knowledge_chunks 
                (document_id, product_id, chunk_index, content, char_count, metadata,
                 source_language, embedding_source, embed_status, created_at, updated_at)
                VALUES (%s,%s,%s,%s,%s,%s,'zh','tei','indexed',NOW(),NOW())
            """, (doc_id, product_id, idx, c, len(c),
                  json.dumps({"category": cat, "source": "ind-seed"})))
            chunk_count += 1
    
    cur.execute("UPDATE rag_products SET doc_count=%s, chunk_count=%s, updated_at=NOW() WHERE id=%s",
                (doc_count, chunk_count, product_id))
    return doc_count, chunk_count

