def batch(table, cols, rows):
    if not rows: return 0
    cur.executemany(f"INSERT INTO {table} ({','.join(cols)}) VALUES ({','.join(['%s']*len(cols))})", rows)
    return cur.rowcount

def batch_no_conflict(table, cols, rows):
    if not rows: return 0
    placeholders = ','.join(['%s'] * len(cols))
    col_str = ','.join(cols)
    cur.executemany(f"INSERT INTO {table} ({col_str}) VALUES ({placeholders})", rows)
    return cur.rowcount

def fill(tmpl, fillers):
    return re.sub(r'\{(\w+)\}', lambda m: fillers.get(m.group(1), m.group(0)), tmpl)

